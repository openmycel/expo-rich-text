// Writes THIRD-PARTY-LICENSES.md: every npm package that esbuild bundles into the editor
// page (web/ → src/editor-html.ts), with its license text verbatim. The page ships minified
// without comments, so the notices live here; the MIT license requires them in every copy.
//
// Run: node scripts/third-party-licenses.mjs (also part of `npm run build:web`)

import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LICENSE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md"];

const packages = new Map();
for (const entry of ["web/prerender.ts", "web/editor.ts"]) {
  const result = await build({
    entryPoints: [join(root, entry)],
    bundle: true,
    write: false,
    metafile: true,
    logLevel: "silent",
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    if (!match || packages.has(match[1])) continue;
    const dir = join(root, "node_modules", match[1]);
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const file = LICENSE_FILES.map((name) => join(dir, name)).find(existsSync);
    if (!file) throw new Error(`${match[1]}: no license file`);
    packages.set(match[1], {
      version: manifest.version,
      license: manifest.license,
      text: readFileSync(file, "utf8").trim(),
    });
  }
}

// One copy of each distinct text, with the packages it covers.
const texts = new Map();
for (const [name, info] of [...packages].sort()) {
  const group = texts.get(info.text) ?? { packages: [], license: info.license };
  group.packages.push(`${name}@${info.version}`);
  texts.set(info.text, group);
}

let out = `# Third-party licenses

The editor page (\`src/editor-html.ts\`, built by \`scripts/build-web.mjs\`) bundles the packages
below, minified and without comments. Their license texts follow, verbatim. Generated by
\`scripts/third-party-licenses.mjs\` from the packages actually in the bundle.

`;
for (const [text, group] of texts) {
  out += `## ${group.packages.join(", ")}\n\n${group.license}\n\n\`\`\`\n${text}\n\`\`\`\n\n`;
}
writeFileSync(join(root, "THIRD-PARTY-LICENSES.md"), out);
console.log(`third-party licenses: ${packages.size} packages, ${texts.size} license texts`);
